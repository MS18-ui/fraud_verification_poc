"""
master_dataset_adapter.py

Integration for the real master dataset (master_results.csv, 30,355 records:
19,847 business / 10,508 person; 512 labeled fraud). Unlike the placeholder
assumed earlier, this file does NOT contain raw vendor JSON -- it's already
flattened to the same flags/scores/match-tiers level that
engine/canonical_mapper.py normally derives FROM raw JSON. So this adapter
builds the canonical dict directly from the flat columns, skipping
canonical_mapper.py's raw-response parsing entirely (there is no raw
response here to parse) -- but producing the exact same shape, so
engine/decision.py and scoring/fraud_model.py consume it unchanged.

The `sources` column ("giact|ekata", "ews", "giact|ews|ekata", ...) records
which vendors actually contributed to a given row; a vendor's columns are
NaN when it wasn't one of the sources for that record -- handled the same
way engine/orchestrator_stub.py already handles a skipped vendor call (that
vendor's canonical fields fall back to their "not available" default).

Columns present in the real file but with NO canonical schema slot (e.g.
is_commercial_address, recent_previous_address_count_90d, ssn fields,
email_is_autogenerated) are listed in UNMAPPED_CANONICAL_FIELDS below --
they default to the same values build_canonical() uses when a vendor is
absent, and are flagged once via a printed warning the first time this
module is imported, not silently.
"""

from __future__ import annotations
import warnings
from pathlib import Path
from typing import Any, Optional

import pandas as pd

UNMAPPED_CANONICAL_FIELDS = [
    "identity.ssn_status", "owner.address_match_status (approximated)",
    "owner.is_commercial_address", "owner.is_forwarder_address", "owner.address_type",
    "owner.recent_previous_address_count_90d", "account.account_closed_date",
    "account.funds_confirmation_result", "supplementary.ssn_issue_state",
    "supplementary.ssn_issue_start_year", "supplementary.date_of_birth",
    "supplementary.known_address_states", "supplementary.email_is_autogenerated",
    "supplementary.adverse_alert_codes (itemized codes not in this dataset, only counts)",
]
warnings.warn(
    f"master_dataset_adapter: {len(UNMAPPED_CANONICAL_FIELDS)} canonical fields have no "
    f"source column in master_results.csv and use safe defaults -- see UNMAPPED_CANONICAL_FIELDS.",
    stacklevel=2,
)


def _b(row: pd.Series, col: str) -> bool:
    v = row.get(col)
    return bool(v) if pd.notna(v) else False


def _s(row: pd.Series, col: str) -> Optional[str]:
    v = row.get(col)
    return str(v) if pd.notna(v) else None


def _n(row: pd.Series, col: str) -> Optional[float]:
    v = row.get(col)
    return float(v) if pd.notna(v) else None


def _i(row: pd.Series, col: str, default: int = 0) -> int:
    v = row.get(col)
    return int(v) if pd.notna(v) else default


def canonical_from_master_row(row: pd.Series) -> dict[str, Any]:
    """Builds the exact canonical shape build_canonical() would, directly
    from one row of the already-flattened master dataset."""
    sources = str(row.get("sources", ""))
    has_giact, has_ekata, has_ews = "giact" in sources, "ekata" in sources, "ews" in sources

    name_match = _b(row, "giact_flag_name_match") if has_giact else False
    phone_name_match = _b(row, "ekata_flag_phone_name_match") if has_ekata else False
    email_name_match = _b(row, "ekata_flag_email_name_match") if has_ekata else False
    address_name_match = _b(row, "ekata_flag_address_name_match") if has_ekata else False
    n_alerts = _i(row, "giact_n_consumer_alerts") + _i(row, "ekata_n_alerts")

    canonical = {
        "schema_version": "1.0",
        "entity_id": str(row["entity_id"]),

        "identity": {
            "record_found": _b(row, "giact_flag_record_found") if has_giact else False,
            "name_match": name_match,
            "ofac_hit": _b(row, "giact_flag_ofac_hit") if has_giact else False,
            "ssn_status": None,  # not present in this dataset
            "identity_check_score": _n(row, "ekata_identity_check_score") if has_ekata else None,
            "identity_network_score": _n(row, "ekata_identity_network_score") if has_ekata else None,
            "low_identity_score": _b(row, "ekata_flag_low_identity_score") if has_ekata else False,
            "phone_name_match": phone_name_match,
            "email_name_match": email_name_match,
            "address_name_match": address_name_match,
            "name_match_any": name_match or (phone_name_match and email_name_match),
            "alerts": [],  # itemized alert list not in this dataset, only counts (below)
            "alerts_count": n_alerts,
        },

        "owner": {
            "name_match": name_match,
            "address_match": _b(row, "giact_flag_address_match") if has_giact else False,
            "address_match_status": ("current" if _b(row, "giact_flag_address_match") else "not_found") if has_giact else "not_found",
            "consumer_alert": _b(row, "giact_flag_consumer_alert") if has_giact else False,
            "ekata_address_name_match": address_name_match,
            "ekata_address_match_to_name": ("Match" if address_name_match else "No Match") if has_ekata else "Unknown",
            "is_commercial_address": False,   # not present in this dataset
            "is_forwarder_address": False,     # not present in this dataset
            "address_type": None,              # not present in this dataset
            "recent_previous_address_count_90d": 0,  # not present in this dataset
        },

        "account": {
            "verification_response": _s(row, "giact_verification_response") or "Unknown",
            "account_verified": _b(row, "giact_flag_account_verified") if has_giact else False,
            "response_code": _s(row, "giact_account_response_code"),
            "account_closed_date": None,  # not present in this dataset
            "funds_confirmation_result": None,  # not present in this dataset
            "account_added_date": _s(row, "giact_account_added_date"),
            "account_last_updated_date": _s(row, "giact_account_last_updated_date"),
            "ews_fraud_history": _b(row, "ews_flag_risk_indicators") if has_ews else None,
        },

        "supplementary": {
            "ssn_issue_state": None, "ssn_issue_start_year": None, "date_of_birth": None,
            "known_address_states": [],
            "prepaid_phone": (row.get("ekata_phone_line_type") == "Premium") if has_ekata else False,
            "phone_match_to_address": _b(row, "ekata_flag_phone_address_match") if has_ekata else None,
            "phone_line_type": _s(row, "ekata_phone_line_type"),
            "submitted_phone_classification": None,
            "account_holder_type": "business" if row.get("entity_type") == "business" else "person",
            "email_is_disposable": _b(row, "ekata_flag_email_disposable") if has_ekata else False,
            "email_is_autogenerated": False,  # not present in this dataset
            "email_first_seen_days": _n(row, "ekata_email_first_seen_days") if has_ekata else None,
            "mailbox_velocity": _n(row, "ekata_mailbox_velocity") if has_ekata else None,
            "email_risk_score": _n(row, "ekata_email_risk_score") if has_ekata else None,
            "ip_proxy_risk": _b(row, "ekata_flag_ip_proxy_risk") if has_ekata else False,
            "ip_error": None, "ip_warnings": [],
            "distance_from_primary_address_miles": _n(row, "ekata_ip_distance_from_primary_address") if has_ekata else None,
            "distance_from_primary_phone_miles": None,
            "travel_alert_on_file": False,
            "ofac_potential_matches_count": _i(row, "giact_n_ofac_matches"),
            "adverse_alert_codes": [],
        },

        "_provenance": {"_dataset_row_sources": sources},
    }
    return canonical


def load_master_records(path: str) -> list[dict[str, Any]]:
    """Returns one dict per case: {entity_id, canonical, is_fraud, meta}.
    Unlike the raw-JSON version, `canonical` is already fully built -- no
    build_canonical() call is needed downstream."""
    df = pd.read_csv(path, low_memory=False)
    records = []
    for _, row in df.iterrows():
        records.append({
            "entity_id": str(row["entity_id"]),
            "account_holder_type": "business" if row.get("entity_type") == "business" else "person",
            "canonical": canonical_from_master_row(row),
            "is_fraud": bool(row["is_fraud"]) if pd.notna(row.get("is_fraud")) else None,
            "meta": {"typology": _s(row, "typology"), "profile": _s(row, "profile"),
                     "sources": _s(row, "sources"), "n_sources": _i(row, "n_sources")},
        })
    return records


def build_training_frame(path: str) -> "pd.DataFrame":
    """Runs every labeled record's canonical profile through the fraud
    feature builder and attaches is_fraud -- ready for the XGBoost training
    script (build guide, Section 8.3). No vendor calls or build_canonical()
    needed -- this dataset is already at that level."""
    from scoring.fraud_model import _features_from_canonical

    rows = []
    skipped = 0
    for rec in load_master_records(path):
        if rec["is_fraud"] is None:
            skipped += 1
            continue
        features = _features_from_canonical(rec["canonical"])
        features["is_fraud"] = int(rec["is_fraud"])
        features["entity_id"] = rec["entity_id"]
        features["typology"] = rec["meta"]["typology"]
        rows.append(features)

    if skipped:
        print(f"Skipped {skipped} unlabeled records.")
    return pd.DataFrame(rows)
